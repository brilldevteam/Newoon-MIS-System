const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const scope = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('frontend/src/utils/kyc-form-diff.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, scope);
const { compareKycForms } = scope.exports;
const first = { sectionA: { legalName: 'Original' }, sectionB: { shareholders: [{ id: 'a', fullName: 'Person', identityNumber: '0001', ownershipPercentage: 100 }] }, sectionG: { signatureDataUrl: 'original-image' } };
const second = structuredClone(first);
second.sectionA.legalName = 'Amended';
second.sectionB.shareholders[0].ownershipPercentage = 70;
second.sectionB.shareholders.push({ id: 'b', fullName: 'New Person', identityNumber: '0002', ownershipPercentage: 30 });
second.sectionG.signatureDataUrl = 'new-image';
const changes = compareKycForms(first, second);
assert.equal(changes.length, 4);
assert.equal(changes.filter((change) => change.kind === 'added').length, 1);
const reordered = structuredClone(second);
reordered.sectionB.shareholders.reverse();
reordered.sectionB.shareholders.forEach((row) => { row.updatedAt = 'changed'; });
assert.equal(compareKycForms(second, reordered).length, 0);
assert.equal(compareKycForms({ preliminaryDocument: { companyName: 'Original' } }, { preliminaryDocument: { companyName: 'Amended' } }).length, 1);
assert.equal(compareKycForms(first, first).length, 0);
const duplicates = { sectionB: { shareholders: [{ id: 'a', fullName: 'Same name', ownershipPercentage: 30 }, { id: 'b', fullName: 'Same name', ownershipPercentage: 70 }] } };
assert.equal(compareKycForms(duplicates, { sectionB: { shareholders: [...duplicates.sectionB.shareholders].reverse() } }).length, 0);
assert.ok(compareKycForms(second, first).some((change) => change.kind === 'removed'));
console.log('Field, ownership, signature, new/removed rows, preliminary and row-order diff checks passed.');
